// Inline built-in skill files into a TypeScript module. The API is bundled to
// dist/index.js, so runtime code cannot read these files from disk.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../src/builtin-skills");
const out = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../src/builtin-skill-assets.ts",
);
const MAX_FILES = 40;
const MAX_FILE_BYTES = 100_000;
const MAX_TOTAL_BYTES = 400_000;
const TEXT_FILE = /\.(md|mdx|txt|json|ya?ml|csv)$/i;

function walk(directory) {
  const files = [];
  for (const entry of readdirSync(directory)) {
    const full = path.join(directory, entry);
    if (statSync(full).isDirectory()) files.push(...walk(full));
    else files.push(full);
  }
  return files;
}

function companions(skillDir) {
  const result = {};
  for (const full of walk(skillDir).sort()) {
    const relative = path.relative(skillDir, full).split(path.sep).join("/");
    if (relative === "SKILL.md") continue;
    const base = path.posix.basename(relative);
    if (base !== "LICENSE" && !TEXT_FILE.test(relative)) {
      throw new Error(`${relative} is not a text reference file`);
    }
    const text = readFileSync(full, "utf8");
    if (Buffer.byteLength(text) > MAX_FILE_BYTES) {
      throw new Error(`${relative} exceeds ${MAX_FILE_BYTES} bytes`);
    }
    result[relative] = text;
  }
  const paths = Object.keys(result);
  if (paths.length > MAX_FILES) throw new Error(`${skillDir} has ${paths.length} files`);
  const total = paths.reduce((sum, key) => sum + Buffer.byteLength(result[key]), 0);
  if (total > MAX_TOTAL_BYTES) throw new Error(`${skillDir} files total ${total} bytes`);
  return result;
}

const skills = {};
for (const name of readdirSync(root).sort()) {
  const skillDir = path.join(root, name);
  if (!statSync(skillDir).isDirectory()) continue;
  skills[name] = {
    content: readFileSync(path.join(skillDir, "SKILL.md"), "utf8"),
    files: companions(skillDir),
  };
}

const source = `// Generated by packages/adapters/scripts/embed-builtin-skills.mjs. Do not edit.
// Skill markdown lives in packages/adapters/src/builtin-skills/. Regenerate
// this module after changing those files; the API bundle inlines these strings.

export const EMBEDDED_BUILTIN_SKILLS: Readonly<
  Record<string, { readonly content: string; readonly files: Readonly<Record<string, string>> }>
> = ${JSON.stringify(skills, null, 2)};
`;

writeFileSync(out, source);
process.stdout.write(
  `wrote ${path.relative(process.cwd(), out)} (${Object.keys(skills).join(", ")})\n`,
);
