export type AlmaCopyKey = keyof typeof copy.en;

export function almaText(key: AlmaCopyKey, locale: string): string {
  if (locale === "es" || locale.toLowerCase().startsWith("es")) return copy.es[key];
  return copy.en[key];
}

export function almaCatalog(locale: string): typeof copy.en {
  return locale === "es" || locale.toLowerCase().startsWith("es") ? copy.es : copy.en;
}
